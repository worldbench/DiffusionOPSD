"""INTERNAL EVALUATOR: InternVL2-26B pairwise reward.

The fine-tuned judge checkpoint and its reference-image corpus are internal and
are not among the seven public presets. ``INTERNVL_DUAL_CKPT`` must be set; the
adapter fails closed before loading the 26B base model.

Wraps a dual/pairwise InternVL judge (checkpoint supplied through ``INTERNVL_DUAL_CKPT``;
InternVL2-26B = InternViT-6B +
InternLM2-20B). It is shown TWO images for the same prompt — [generated, reference] — and asked
"is the first image better than the second? 是/否". The reward is **P(是/yes)** =
softmax(logit[是], logit[否])[是] at the final token, i.e. P(generated > reference).

Gradient mechanism is IDENTICAL to the pointwise scorer (src/internvl_t2i_scorer.py): a
MANUAL differentiable InternVL forward — `extract_feature(pixel_values)` → scatter ViT embeds
into the `<IMG_CONTEXT>` slots → `language_model(inputs_embeds=…)` → read the yes/no logits →
softmax. Gradient flows reward → yes/no logit → LM → vit_embeds → pixel_values → IMAGE. Model
frozen. So OPA can drive `autograd.grad(reward, generated_image)`.

Only the GENERATED image carries grad; the REFERENCE image is fixed data (detached). Maximizing
the reward pushes the generated image to beat its reference — a relative signal (unlike the
pointwise absolute P(score=5)).

MEMORY: 26B (~52 GB) + TWO images (2× ViT tiles) is heavier than pointwise and is intended for
dedicated reward GPUs rather than co-location per policy rank. This module is the reward core; the
deployment (2-GPU server / gradient bridge vs co-locate) wraps it.
"""

