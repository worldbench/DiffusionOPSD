def _has_chinese(s: str) -> bool:
    return any("一" <= c <= "鿿" for c in s)


class InternVLDualScorer(torch.nn.Module):
    """Differentiable pairwise reward P(generated > reference) from the InternVL2-26B dual judge."""

    def __init__(self, checkpoint_path: str = DEFAULT_CHECKPOINT, base_arch: str = DEFAULT_BASE_ARCH,
                 device: str = "cuda", dtype: torch.dtype = torch.bfloat16,
                 device_map_devices=None,  # GATED (INTERNVL_BRIDGE server): shard 26B over these GPUs
                 template_type: int = int(os.environ.get("INTERNVL_DUAL_TEMPLATE", "0")),
                 tag_idxs: str = os.environ.get("INTERNVL_DUAL_TAGS", "1")):
        super().__init__()
        if not checkpoint_path:
            raise RuntimeError(
                "INTERNVL_DUAL_CKPT is required. The paper's pairwise evaluator checkpoint is internal."
            )
        if not os.path.isfile(checkpoint_path):
            raise FileNotFoundError(f"INTERNVL_DUAL_CKPT does not exist: {checkpoint_path}")
        self.device = device
        self.dtype = dtype
        assert template_type in _TEMPLATES, f"template_type must be in {list(_TEMPLATES)}"
        self.template_type = template_type
        self.tag_idxs = [int(t) for t in str(tag_idxs).split(",") if t.strip()]  # only used by type 0

        base_arch = _resolve_base_arch(base_arch)
        use_flash = os.environ.get("INTERNVL_DUAL_FLASH", "0") == "1"
        config = AutoConfig.from_pretrained(base_arch, trust_remote_code=True)
        from transformers.modeling_utils import no_init_weights
        with no_init_weights():
            try:
                self.model = AutoModel.from_config(config, torch_dtype=dtype, use_flash_attn=use_flash,
                                                   trust_remote_code=True)
            except TypeError:
                self.model = AutoModel.from_config(config, torch_dtype=dtype, trust_remote_code=True)
        _load_finetuned_state_dict(self.model, checkpoint_path)
        if device_map_devices and len(device_map_devices) > 1:
            # GATED (INTERNVL_BRIDGE server): shard the frozen 26B across the reward GPUs, mirroring
            # the pointwise scorer's _dispatch_multi_gpu. IO modules (ViT, mlp1, LM token-embeddings,
            # final norm, LM head) are PINNED to `primary`, so _score_one's manual two-image forward
            # (pixel_values/input_ids/score-token buffers on primary, <IMG_CONTEXT> scatter on
            # primary, logits back on primary) needs ZERO changes; only decoder LAYERS split, and
            # accelerate's AlignDevicesHook moves the hidden state across GPUs with a differentiable
            # .to() so the reward->gen gradient flows across the device boundary exactly as on one GPU.
            from accelerate import dispatch_model
            from diffusionopsd.internvl_t2i_scorer import _build_internvl_device_map
            primary = int(str(device).split(":")[-1]) if isinstance(device, str) and ":" in str(device) else 0
            self.model = self.model.to(dtype=dtype)  # cast on CPU before dispatch (never a single .to(cuda))
            dmap = _build_internvl_device_map(self.model, primary, [int(d) for d in device_map_devices])
            self.model = dispatch_model(self.model, device_map=dmap).eval()
            print(f"[internvl_dual] sharded 26B across {list(device_map_devices)} (primary={primary}); "
                  f"{sum(v != primary for v in dmap.values())} modules off-primary", flush=True)
        else:
            self.model = self.model.to(device=device, dtype=dtype).eval()
        self.model.requires_grad_(False)
        if os.environ.get("INTERNVL_DUAL_GRADCKPT", "1") == "1":
            _force_nonreentrant_checkpoint()
            try:
                self.model.vision_model.gradient_checkpointing = True
                self.model.language_model.config.use_cache = False
                self.model.language_model.gradient_checkpointing = True
                self.model.language_model.model.gradient_checkpointing = True
            except Exception as exc:  # pragma: no cover
                print(f"[internvl_dual] grad-ckpt enable skipped: {exc}")
            self.model.train()

        self.tokenizer = AutoTokenizer.from_pretrained(base_arch, trust_remote_code=True, use_fast=False)
        self.img_context_token_id = self.tokenizer.convert_tokens_to_ids(IMG_CONTEXT_TOKEN)
        self.model.img_context_token_id = self.img_context_token_id
        self.num_image_token = int(self.model.num_image_token)  # 256 for 448 tile
        # yes/no token ids (last token of the encoding), matching the reference reader
        enc = lambda t: self.tokenizer(t, return_attention_mask=False, add_special_tokens=False)["input_ids"][-1]
        self.en_yes, self.en_no = enc("yes"), enc("no")
        self.cn_yes, self.cn_no = enc("是"), enc("否")

        self.register_buffer("_mean", torch.tensor(IMAGENET_MEAN).view(1, 3, 1, 1), persistent=False)
        self.register_buffer("_std", torch.tensor(IMAGENET_STD).view(1, 3, 1, 1), persistent=False)

    def _preprocess_one(self, image01: torch.Tensor) -> torch.Tensor:
        """[1,3,H,W] in [0,1] -> [1,3,448,448] model-dtype (pad->512->448->ImageNet-norm, single tile)."""
        x = image01.to(torch.float32)
        x = _pad_to_square(x, value=1.0)
        # reference path: resize to r_size=512 then dynamic_preprocess to a single 448 tile (square)
        x = F.interpolate(x, size=(R_SIZE, R_SIZE), mode="bicubic", align_corners=False, antialias=True)
        x = F.interpolate(x, size=(TILE, TILE), mode="bicubic", align_corners=False, antialias=True).clamp(0, 1)
        x = (x - self._mean.to(x)) / self._std.to(x)
        return x.to(self.dtype)

    def _build_prompt(self, prompt: str, chinese: bool) -> str:
        cn_t, en_t = _TEMPLATES[self.template_type]
        instruct = cn_t if chinese else en_t
        if self.template_type == 0:  # substitute the <tags> criteria list from tag_idxs
            tag2cond = _CN_TAG2COND if chinese else _EN_TAG2COND
            cat_tag = "".join(tag2cond[i] for i in self.tag_idxs)[:-1]  # drop trailing comma
            instruct = instruct.replace("<tags>", cat_tag)
        # quote the prompt like the reference (adds a trailing period + Chinese/English quotes)
        p = prompt
        if chinese:
            p = f"“{p}。”" if not p.endswith(("。", "，", "！", "？")) else f"“{p}”"
        else:
            p = f'"{p}."' if not p.endswith((".", ",", "!", "?")) else f'"{p}"'
        instruct = instruct.replace("<prompt>", p)
        cur = PROMPT_TEMPLATE.replace("<user_prompt>", instruct)
        image_tokens = IMG_START_TOKEN + IMG_CONTEXT_TOKEN * self.num_image_token + IMG_END_TOKEN
        # two <image> slots: first = generated, second = reference
        cur = cur.replace("<image>", image_tokens, 1).replace("<image>", image_tokens, 1)
        return cur

    def _score_one(self, gen01: torch.Tensor, ref01: torch.Tensor, prompt: str) -> torch.Tensor:
        chinese = _has_chinese(prompt)
        gen_px = self._preprocess_one(gen01)                 # grad flows here
        ref_px = self._preprocess_one(ref01).detach()        # reference is fixed data

        cur_prompt = self._build_prompt(prompt, chinese)
        enc = self.tokenizer(cur_prompt, return_tensors="pt")
        input_ids = enc["input_ids"].to(self.device)
        attention_mask = enc["attention_mask"].to(self.device)

        # extract_feature is per-image independent, so running gen (grad) and ref (no_grad) through the
        # ViT SEPARATELY and concatenating the embeds is numerically identical to a batched [gen,ref]
        # forward — but the ref half then holds NO backward activations. This ~halves the ViT autograd
        # memory of the OPA reward-gradient ascent, which otherwise died with CUDNN_STATUS_INTERNAL_ERROR
        # (memory pressure) on the 2-image dual reward. Order stays [generated, reference].
        gen_embeds = self.model.extract_feature(gen_px)
        with torch.no_grad():
            ref_embeds = self.model.extract_feature(ref_px)
        vit_embeds = torch.cat([gen_embeds, ref_embeds], dim=0)
        input_embeds = self.model.language_model.get_input_embeddings()(input_ids)
        B, N, C = input_embeds.shape
        flat = input_embeds.reshape(B * N, C).clone()
        selected = input_ids.reshape(B * N) == self.img_context_token_id
        assert int(selected.sum()) == vit_embeds.reshape(-1, C).shape[0], "IMG_CONTEXT/vit token mismatch"
        flat[selected] = vit_embeds.reshape(-1, C).to(flat.dtype)
        input_embeds = flat.reshape(B, N, C).to(self.dtype)

        out = self.model.language_model(inputs_embeds=input_embeds, attention_mask=attention_mask)
        logits = out.logits if hasattr(out, "logits") else out[0]
        last = logits[0, -1, :]                              # final-token logits
        yes_id, no_id = (self.cn_yes, self.cn_no) if chinese else (self.en_yes, self.en_no)
        pair = torch.stack([last[yes_id], last[no_id]]).float()
        return torch.softmax(pair, dim=-1)[0]                # P(yes) = P(generated > reference)

    def _scores(self, gen01: torch.Tensor, ref01: torch.Tensor, prompts: Sequence[str]) -> torch.Tensor:
        """Batched InternVL pairwise forward (right-pad + per-sample last-token read)
        so opa_mb>1 batches the 26B. One-time runtime parity check vs per-sample (fails loud)."""
        if isinstance(prompts, str):
            prompts = [prompts]
        prompts = list(prompts)
        if gen01.dim() == 3:
            gen01 = gen01.unsqueeze(0)
        if ref01.dim() == 3:
            ref01 = ref01.unsqueeze(0)
        gen01, ref01 = gen01.to(self.device), ref01.to(self.device)
        B = gen01.shape[0]
        if B == 1:
            return self._score_one(gen01, ref01, prompts[0]).reshape(1)
        if os.environ.get("INTERNVL_C_BATCHED", "0") != "1":
            # Batched _scores is disabled by default; see internvl_t2i_scorer for rationale.
            # (batched forward diverges > the 5e-3 parity bound on some 26B batches; the bridge server
            # always calls _scores with B>1). Exact per-sample loop; set INTERNVL_C_BATCHED=1 to debug.
            return torch.cat([self._score_one(gen01[i:i + 1], ref01[i:i + 1], prompts[i]).reshape(1) for i in range(B)])  # [B]
        out = self._scores_batched(gen01, ref01, prompts)
        if not getattr(self, "_batch_parity_ok", False):
            with torch.no_grad():
                ref = torch.stack([self._score_one(gen01[i:i + 1], ref01[i:i + 1], prompts[i]) for i in range(B)])
            if not (torch.isfinite(out).all() and torch.isfinite(ref).all()):
                raise RuntimeError("[internvl_dual C] non-finite reward in batched/per-sample parity check")
            md = (out.detach() - ref).abs().max().item()
            if not (md <= 5e-3):  # `not <=` also trips on NaN md
                raise RuntimeError(f"[internvl_dual C] batched vs per-sample reward max diff {md:.4g} > 5e-3")
            self._batch_parity_ok = True
        return out

    def _scores_batched(self, gen01: torch.Tensor, ref01: torch.Tensor, prompts: Sequence[str]) -> torch.Tensor:
        """One right-padded pairwise forward over the batch. Order per sample = [generated, reference];
        gen keeps grad, ref is no-grad (half the ViT autograd memory, matches _score_one)."""
        B = gen01.shape[0]
        gen_px = torch.cat([self._preprocess_one(gen01[i:i + 1]) for i in range(B)], dim=0)              # [B,3,448,448] grad
        ref_px = torch.cat([self._preprocess_one(ref01[i:i + 1]).detach() for i in range(B)], dim=0)     # [B,3,448,448] no-grad
        gen_embeds = self.model.extract_feature(gen_px)                 # [B,T,C] grad
        with torch.no_grad():
            ref_embeds = self.model.extract_feature(ref_px)            # [B,T,C] no-grad
        T, C = gen_embeds.shape[1], gen_embeds.shape[-1]
        vit = torch.stack([gen_embeds, ref_embeds], dim=1).reshape(B * 2 * T, C)  # [gen0,ref0,gen1,ref1,...]
        pad_id = self.tokenizer.pad_token_id
        if pad_id is None:
            pad_id = self.tokenizer.eos_token_id
        seqs, chinese = [], []
        for i in range(B):
            ch = _has_chinese(prompts[i]); chinese.append(ch)
            seqs.append(self.tokenizer(self._build_prompt(prompts[i], ch), return_tensors="pt")["input_ids"][0].to(self.device))
        Lmax = max(s.shape[0] for s in seqs)
        input_ids = torch.full((B, Lmax), pad_id, dtype=torch.long, device=self.device)
        attn = torch.zeros((B, Lmax), dtype=torch.long, device=self.device)
        lens = []
        for i, s in enumerate(seqs):
            L = s.shape[0]; lens.append(L); input_ids[i, :L] = s; attn[i, :L] = 1  # RIGHT-pad
        input_embeds = self.model.language_model.get_input_embeddings()(input_ids)  # [B,Lmax,C]
        selected = input_ids.reshape(-1) == self.img_context_token_id
        assert int(selected.sum().item()) == B * 2 * T, f"IMG_CONTEXT {int(selected.sum())} != {B * 2 * T}"
        flat = input_embeds.reshape(B * Lmax, C).clone()
        flat[selected] = vit.to(flat.dtype)                            # sample-order, [gen,ref] within sample
        input_embeds = flat.reshape(B, Lmax, C).to(self.dtype)
        out = self.model.language_model(inputs_embeds=input_embeds, attention_mask=attn)
        logits = out.logits if hasattr(out, "logits") else out[0]      # [B,Lmax,vocab]
        scores = []
        for i in range(B):
            last = logits[i, lens[i] - 1, :]                           # last REAL token (pre-pad)
            yes_id, no_id = (self.cn_yes, self.cn_no) if chinese[i] else (self.en_yes, self.en_no)
            scores.append(torch.softmax(torch.stack([last[yes_id], last[no_id]]).float(), dim=-1)[0])
        return torch.stack(scores)

    @torch.no_grad()
    def __call__(self, gen: torch.Tensor, ref: torch.Tensor, prompts: Sequence[str]) -> torch.Tensor:
        return self._scores(gen, ref, prompts).float()


_DUAL_CACHE: dict = {}


def get_internvl_dual_scorer(device: str = "cuda", checkpoint_path: str = DEFAULT_CHECKPOINT,
                             **kwargs) -> "InternVLDualScorer":
    """Process-level singleton (one 52 GB model/rank) — same rationale as the pointwise scorer."""
    key = (str(device), checkpoint_path)
    s = _DUAL_CACHE.get(key)
    if s is None:
        s = InternVLDualScorer(device=device, checkpoint_path=checkpoint_path, **kwargs)
        _DUAL_CACHE[key] = s
    return s
